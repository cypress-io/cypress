export function getCDPKeyCode (key: KeyPressSupportedKeys): string {
  return `U+${KEY_HEX_TABLE[key].toString(16).padStart(4, '0').toUpperCase()}`
}

export function getBidiValue (key: KeyPressSupportedKeys): string {
  return `\\u${KEY_HEX_TABLE[key].toString(16).padStart(4, '0').toUpperCase()}`
}
